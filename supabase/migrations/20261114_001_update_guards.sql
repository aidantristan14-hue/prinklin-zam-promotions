-- Phase 1 security batch 1: fix request and notification row-update invariants.
-- This follows the existing core migration so its history remains reviewable.
-- Apply only in an isolated test database after review; never against production here.

begin;

-- Trigger functions can compare OLD and NEW; RLS policy expressions cannot.
-- Keep customer-controlled request content editable, but protect ownership, scope,
-- request number, status, assignment, and timestamps as appropriate.
create or replace function public.block_unsafe_request_override()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  -- A database service-role operation with no end-user JWT is a trusted backend
  -- operation. It must remain server-only by privilege configuration outside this
  -- narrowly scoped batch; ordinary authenticated requests always have auth.uid().
  if auth.uid() is null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new.customer_id is distinct from auth.uid() then
      raise exception 'Request owner must be the authenticated user';
    end if;
    if new.status is distinct from 'new'::public.request_status then
      raise exception 'Customer-created requests must start as new';
    end if;
    if new.assigned_to is not null then
      raise exception 'Customers cannot assign staff';
    end if;
    if new.request_number is not null and btrim(new.request_number) <> '' then
      raise exception 'Request number is generated by the database';
    end if;
    if new.closed_at is not null then
      raise exception 'A new customer request cannot be closed';
    end if;

    -- These values are server-managed. Department and category remain selectable
    -- from the catalog on creation; their pair is enforced by the composite FK.
    new.submitted_at := now();
    new.created_at := now();
    new.updated_at := now();
    new.closed_at := null;
    return new;
  end if;

  -- These fields are immutable after creation for all authenticated client roles.
  if new.id is distinct from old.id
     or new.customer_id is distinct from old.customer_id
     or new.department_id is distinct from old.department_id
     or new.service_category_id is distinct from old.service_category_id
     or new.request_number is distinct from old.request_number
     or new.created_at is distinct from old.created_at
     or new.submitted_at is distinct from old.submitted_at then
    raise exception 'Request identity, ownership, scope, category, number, and creation timestamps are immutable';
  end if;

  -- Customer-owned rows may only receive ordinary content edits while still new.
  -- Staff status/assignment/closure actions remain available through the existing
  -- department-scoped staff UPDATE policy.
  if auth.uid() = old.customer_id then
    if new.status is distinct from old.status
       or new.assigned_to is distinct from old.assigned_to
       or new.closed_at is distinct from old.closed_at then
      raise exception 'Customers cannot change request status, assignment, or closure';
    end if;
    if old.status <> 'new'::public.request_status then
      raise exception 'Customers may only edit new requests';
    end if;
  end if;

  -- updated_at is maintained by its existing BEFORE UPDATE trigger, not the client.
  new.updated_at := old.updated_at;
  return new;
end;
$$;

-- The original customer UPDATE policy's request_number self-comparison was a no-op.
-- Trigger checks above enforce old/new immutability; this policy constrains the
-- resulting row and keeps customer edits limited to their own still-new requests.
drop policy if exists "service_requests_customer_update_own_only" on public.service_requests;
create policy "service_requests_customer_update_own_only"
on public.service_requests
for update
to authenticated
using (
  customer_id = auth.uid()
  and status = 'new'::public.request_status
)
with check (
  customer_id = auth.uid()
  and status = 'new'::public.request_status
  and assigned_to is null
  and closed_at is null
  and request_number is not null
  and btrim(request_number) <> ''
);

-- Staff remain able to update operational fields, but the new row must still be
-- within the actor's authorized department. Immutable cross-row fields are guarded
-- by block_unsafe_request_override(), not tautological policy comparisons.
drop policy if exists "service_requests_staff_update_authorized" on public.service_requests;
create policy "service_requests_staff_update_authorized"
on public.service_requests
for update
to authenticated
using (
  public.is_super_admin(auth.uid())
  or public.is_administrator(auth.uid())
  or public.has_role_in_department(auth.uid(), 'department_administrator', department_id)
  or public.has_role_in_department(auth.uid(), 'support_agent', department_id)
)
with check (
  public.is_super_admin(auth.uid())
  or public.is_administrator(auth.uid())
  or public.has_role_in_department(auth.uid(), 'department_administrator', department_id)
  or public.has_role_in_department(auth.uid(), 'support_agent', department_id)
);

-- Support thread owner and department scope cannot be moved by an authenticated
-- client. Staff still update operational thread fields inside their existing scope.
create or replace function public.guard_support_thread_scope_update()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is not null and (
    new.id is distinct from old.id
    or new.customer_id is distinct from old.customer_id
    or new.department_id is distinct from old.department_id
    or new.service_request_id is distinct from old.service_request_id
    or new.created_at is distinct from old.created_at
  ) then
    raise exception 'Support thread identity, owner, department, request, and creation time are immutable';
  end if;
  return new;
end;
$$;

drop trigger if exists support_threads_scope_update_guard on public.support_threads;
create trigger support_threads_scope_update_guard
before update on public.support_threads
for each row execute function public.guard_support_thread_scope_update();

drop policy if exists "support_threads_staff_update_authorized" on public.support_threads;
create policy "support_threads_staff_update_authorized"
on public.support_threads
for update
to authenticated
using (
  public.is_super_admin(auth.uid())
  or public.is_administrator(auth.uid())
  or public.has_role_in_department(auth.uid(), 'department_administrator', department_id)
  or public.has_role_in_department(auth.uid(), 'support_agent', department_id)
)
with check (
  public.is_super_admin(auth.uid())
  or public.is_administrator(auth.uid())
  or public.has_role_in_department(auth.uid(), 'department_administrator', department_id)
  or public.has_role_in_department(auth.uid(), 'support_agent', department_id)
);

-- OLD/NEW comparisons belong in a trigger. The customer policy itself only checks
-- row ownership, so read_at may be set or cleared; the trigger rejects any other
-- changed field for authenticated end users.
create or replace function public.guard_notification_read_at_only()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is not null then
    if old.user_id is distinct from auth.uid() then
      raise exception 'Users may only update their own notifications';
    end if;
    if (to_jsonb(new) - 'read_at' - 'updated_at')
       is distinct from
       (to_jsonb(old) - 'read_at' - 'updated_at') then
      raise exception 'Only notification read_at may be changed by the recipient';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists notifications_guard_read_at_only on public.notifications;
create trigger notifications_guard_read_at_only
before update on public.notifications
for each row execute function public.guard_notification_read_at_only();

drop policy if exists "notifications_update_own_read_state" on public.notifications;
create policy "notifications_update_own_read_state"
on public.notifications
for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

commit;
